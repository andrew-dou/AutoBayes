#!/usr/bin/env python
"""Write the upstream log's LaTeX (and, on request, its PDF) from docs/brms-parity/upstream/log.json.

    python tools/upstream_log.py            # write docs/brms-parity/upstream/upstream-log.tex
    python tools/upstream_log.py --check    # exit 1 if the committed .tex is not what log.json gives
    python tools/upstream_log.py --pdf      # also run pdflatex twice and delete the .aux, .log and .out files

The output depends on log.json only, so the .tex is reproduced byte for byte. Text fields are plain ASCII; a span in
backticks is set in typewriter type. The log is validated first: the schema, every field, sequential ids, and for every
entry with a reproduction its script and saved output on disk.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DIR = REPO / "docs" / "brms-parity" / "upstream"
LOG = DIR / "log.json"
TEX = DIR / "upstream-log.tex"
SCHEMA = "autobayes-upstream-log-v1"
FIELDS = ["id", "title", "component", "functions", "versions", "divergences", "found", "kind", "what", "observed",
          "expected", "status", "repro", "upstream", "fix", "known_upstream"]
COMPONENTS = ["brms", "Stan Math", "rstan", "loo", "posterior"]
KINDS = ["wrong result", "inexact numerics", "missing validation"]
STATUSES = ["reproduced", "recorded only", "not a bug after all"]
UPSTREAMS = ["paul-buerkner/brms", "stan-dev/math", "stan-dev/rstan", "stan-dev/loo", "stan-dev/posterior"]
KNOWN = ["not found", "related", "known", "known, fixed upstream"]
ROWS = 10


def validate(log: dict) -> list[str]:
    errors = []
    if log.get("schema") != SCHEMA:
        errors.append(f"schema must be {SCHEMA!r}")
    for key in ("title", "checked", "versions", "about", "entries"):
        if key not in log:
            errors.append(f"top level: missing {key!r}")
    for n, e in enumerate(log.get("entries", []), start=1):
        where = e.get("id", f"entry {n}")
        missing = [f for f in FIELDS if f not in e]
        if missing:
            errors.append(f"{where}: missing {missing}")
            continue
        if e["id"] != f"U{n:02d}":
            errors.append(f"{where}: ids must run U01, U02, ... (expected U{n:02d})")
        for field, allowed in (("component", COMPONENTS), ("kind", KINDS), ("status", STATUSES), ("upstream", UPSTREAMS)):
            if e[field] not in allowed:
                errors.append(f"{where}: {field} {e[field]!r} not one of {allowed}")
        if e["known_upstream"].get("status") not in KNOWN:
            errors.append(f"{where}: known_upstream.status not one of {KNOWN}")
        if e["repro"] is None:
            if e["status"] != "recorded only":
                errors.append(f"{where}: an entry without a reproduction must have status 'recorded only'")
        else:
            script = REPO / e["repro"]
            if not script.is_file() or not script.with_suffix(".out").is_file():
                errors.append(f"{where}: {e['repro']} or its .out is missing")
        text = json.dumps(e)
        if not text.isascii():
            errors.append(f"{where}: text must be ASCII")
    return errors


SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
           "~": r"\textasciitilde{}", "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}",
           "|": r"\textbar{}"}


def escape(s: str) -> str:
    return "".join(SPECIAL.get(c, c) for c in s)


def code(s: str) -> str:
    """Typewriter text that may break after punctuation (TeX does not hyphenate it)."""
    out = []
    for c in s:
        out.append(SPECIAL.get(c, c))
        if c in "_(,=/.;+-*":
            out.append(r"\allowbreak{}")
    return r"\texttt{" + "".join(out) + "}"


def tex(s: str) -> str:
    parts = s.split("`")
    if len(parts) % 2 == 0:
        raise ValueError(f"unbalanced backticks in {s!r}")
    return "".join(code(p) if i % 2 else escape(p) for i, p in enumerate(parts))


def known_block(k: dict) -> str:
    lines = [tex(k["summary"]) + "."]
    for issue in k.get("issues", []):
        lines.append(r"\\ " + r"\url{" + issue["url"] + "} (" + escape(issue["state"]) + "): " + tex(issue["title"]))
    if k.get("fixed_in"):
        lines.append(r"\\ Fixed in: " + tex(k["fixed_in"]) + ".")
    if k.get("note"):
        lines.append(r"\\ " + tex(k["note"]))
    return "\n".join(lines)


def render(log: dict) -> str:
    v = log["versions"]
    out = [r"""% Generated by tools/upstream_log.py from docs/brms-parity/upstream/log.json; do not edit by hand.
\documentclass[10pt]{article}
\usepackage[margin=0.9in]{geometry}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{array,booktabs,enumitem}
\usepackage{xcolor}
\usepackage[colorlinks=true,linkcolor=blue!50!black,urlcolor=blue!50!black]{hyperref}
\sloppy
\setlist{nosep, leftmargin=1.4em}
\setlength{\parskip}{0.5em}
""",
           r"\title{" + tex(log["title"]) + "}",
           r"\author{Generated from \texttt{docs/brms-parity/upstream/log.json} by \texttt{tools/upstream\_log.py}}",
           r"\date{Checked " + escape(log["checked"]) + "}",
           r"\begin{document}", r"\maketitle", ""]
    for para in log["about"]:
        out += [r"\noindent " + tex(para), ""]
    out += [r"\noindent Versions: " + ", ".join(f"{escape(k)} {escape(val)}" for k, val in v.items()) + ".", ""]
    counts = {s: sum(e["status"] == s for e in log["entries"]) for s in STATUSES}
    out += [r"\noindent Entries: " + ", ".join(f"{n} {escape(s)}" for s, n in counts.items() if n) + ".", ""]

    # Ordinary tables of ROWS entries each, so that none breaks across a page (the installed longtable is newer than the
    # LaTeX kernel and fails on a page break).
    out += [r"\section{All entries}", r"\label{sec:table}"]
    entries = log["entries"]
    for start in range(0, len(entries), ROWS):
        out += [r"\begin{center}\small",
                r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.05\textwidth}"
                r">{\raggedright\arraybackslash}p{0.10\textwidth}>{\raggedright\arraybackslash}p{0.38\textwidth}"
                r">{\raggedright\arraybackslash}p{0.11\textwidth}>{\raggedright\arraybackslash}p{0.10\textwidth}"
                r">{\raggedright\arraybackslash}p{0.12\textwidth}@{}}",
                r"\toprule", r"Id & Component & Problem & Kind & Status & Known upstream \\", r"\midrule"]
        for e in entries[start:start + ROWS]:
            out.append(" & ".join([r"\hyperref[" + e["id"] + "]{" + e["id"] + "}", escape(e["component"]), tex(e["title"]),
                                   escape(e["kind"]), escape(e["status"]), tex(e["known_upstream"]["table"])]) + r" \\")
        out += [r"\bottomrule", r"\end{tabular}", r"\end{center}", ""]

    out += [r"\section{The entries}", ""]
    for e in log["entries"]:
        f = e["found"]
        versions = ", ".join(f"{escape(k)} {escape(val)}" for k, val in e["versions"].items())
        repro = (r"\texttt{Rscript " + escape(e["repro"]) + r"} from the repository root; it exits with status 1 while the "
                 r"problem is present. Output of one run: \texttt{" + escape(e["repro"][:-2] + ".out") + "}."
                 if e["repro"] else "No reproduction.")
        out += [r"\subsection{" + e["id"] + ": " + tex(e["title"]) + "}", r"\label{" + e["id"] + "}",
                r"\begin{description}[style=nextline, leftmargin=1.4em, itemsep=2pt]",
                r"\item[Where] " + escape(e["component"]) + ": " + ", ".join(tex(fn) for fn in e["functions"]) +
                ". " + escape(e["kind"].capitalize()) + "; " + escape(e["status"]) + ". Versions: " + versions + ".",
                r"\item[Found by] " + tex(f["feature"]) + (" (" + escape(f["pr"]) + ")" if f.get("pr") else "") +
                ("; divergence " + ", ".join(escape(d) for d in e["divergences"]) if e["divergences"] else "") + "." +
                (" " + tex(f["note"]) if f.get("note") else ""),
                r"\item[What] " + tex(e["what"]),
                r"\item[Observed] " + tex(e["observed"]),
                r"\item[Expected] " + tex(e["expected"]),
                r"\item[Reproduce] " + repro,
                r"\item[Fix] " + tex(e["fix"]),
                r"\item[Belongs in] \url{https://github.com/" + e["upstream"] + "}",
                r"\item[Known upstream] " + known_block(e["known_upstream"]),
                r"\end{description}", ""]
    out += [r"\end{document}", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed .tex instead of writing it")
    ap.add_argument("--pdf", action="store_true", help="also compile the PDF (pdflatex twice) and clean up")
    args = ap.parse_args(argv)
    with open(LOG, encoding="utf-8") as f:
        log = json.load(f)
    errors = validate(log)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    text = render(log)
    if args.check:
        same = TEX.is_file() and TEX.read_text(encoding="utf-8") == text
        print("upstream-log.tex is current" if same else "upstream-log.tex differs from log.json's rendering")
        return 0 if same else 1
    TEX.write_text(text, encoding="utf-8")
    print(f"wrote {TEX.relative_to(REPO)} ({len(log['entries'])} entries)")
    if args.pdf:
        for _ in range(2):
            run = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", TEX.name], cwd=DIR,
                                 capture_output=True, text=True)
            if run.returncode != 0:
                print(run.stdout[-3000:], file=sys.stderr)
                return 1
        log_text = (DIR / "upstream-log.log").read_text(encoding="utf-8", errors="replace")
        undefined = re.findall(r"(?:Reference|Citation) `[^']*' .*undefined", log_text)
        for ext in (".aux", ".log", ".out"):
            (DIR / f"upstream-log{ext}").unlink(missing_ok=True)
        if undefined:
            print("\n".join(undefined), file=sys.stderr)
            return 1
        print(f"wrote {TEX.with_suffix('.pdf').relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
